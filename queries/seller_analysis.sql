-------------------------- Seller Analysis -------------------------

-- Which top 10 sellers generate the highest revenue?
SELECT oi.seller_id, ROUND(SUM(oi.price),2) AS revenue
FROM order_items oi
JOIN orders o ON oi.order_id = o.order_id
WHERE o.order_status = 'delivered'
GROUP BY oi.seller_id 
ORDER BY revenue DESC
LIMIT 10;


-- What percentage of total revenue is contributed by each seller?
SELECT oi.seller_id,
ROUND(SUM(oi.price), 2) AS revenue,
ROUND(SUM(oi.price) / SUM(SUM(oi.price)) OVER() * 100, 2) AS revenue_share_pct
FROM order_items oi
JOIN orders o ON oi.order_id = o.order_id
WHERE o.order_status = 'delivered'
GROUP BY oi.seller_id
ORDER BY revenue_share_pct DESC;


-- What is the order volume per seller?
SELECT oi.seller_id,
COUNT(DISTINCT oi.order_id) AS total_orders
FROM order_items oi
JOIN orders o ON oi.order_id = o.order_id
WHERE o.order_status = 'delivered'
GROUP BY oi.seller_id
ORDER BY total_orders DESC;


-- What percentage of revenue is generated by the top 10 sellers?
WITH ranked AS (
SELECT oi.seller_id, SUM(oi.price) AS revenue
FROM order_items oi
JOIN orders o ON oi.order_id = o.order_id
WHERE o.order_status = 'delivered'
GROUP BY oi.seller_id),
rnk AS (SELECT *, ROW_NUMBER() OVER (ORDER BY revenue DESC) AS rn
FROM ranked)
SELECT ROUND(SUM(CASE WHEN rn <= 10 THEN revenue END) * 100.0 /
SUM(revenue), 2) AS top10_seller_contribution_pct
FROM rnk;


-- Which sellers have the best customer satisfaction scores?
SELECT s.seller_id, ROUND(AVG(orv.review_score), 2) AS avg_review_score,
COUNT(DISTINCT oi.order_id) AS total_orders
FROM sellers s
JOIN order_items oi
ON s.seller_id = oi.seller_id JOIN orders o
ON oi.order_id = o.order_id
JOIN order_reviews orv ON oi.order_id = orv.order_id
WHERE o.order_status = 'delivered'
GROUP BY s.seller_id
HAVING total_orders >= 20
ORDER BY avg_review_score DESC;


-- Seller MoM growth
WITH seller_sales AS (
SELECT DATE_FORMAT(o.order_purchase_timestamp,'%Y-%m') AS month,
oi.seller_id,
ROUND(SUM(oi.price), 2) AS revenue
FROM orders o
JOIN order_items oi
ON o.order_id = oi.order_id
WHERE o.order_status = 'delivered'
GROUP BY month, oi.seller_id)

SELECT month, seller_id, revenue, ROUND((
revenue - LAG(revenue) OVER(PARTITION BY seller_id ORDER BY month)) /
NULLIF(LAG(revenue) OVER(PARTITION BY seller_id ORDER BY month), 0) * 100, 2) AS growth_pct
FROM seller_sales;